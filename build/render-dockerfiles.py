#!/usr/bin/env python3
"""Keep explicitly named distro Dockerfiles synchronized with the default template."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DISTROS = ("fedora-44", "debian-13", "ubuntu-26.04", "archlinux")
UBUNTU_BROWSER = """# Ubuntu's Chromium package is a snap launcher. Fetch only the actual browser
# and its JPEG ABI dependency through Debian's signed APT archive instead.
FROM ghcr.io/skynet-core/systemd:debian-13 AS chromium-packages
RUN apt-get update \\
    && mkdir /chromium-debs \\
    && cd /chromium-debs \\
    && apt-get download chromium chromium-common chromium-sandbox libjpeg62-turbo
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    template = (ROOT / "Dockerfile").read_text()
    failures = []
    for distro in DISTROS:
        content = template.replace(
            "ARG BASE_IMAGE=ghcr.io/skynet-core/systemd:fedora-44",
            f"ARG BASE_IMAGE=ghcr.io/skynet-core/systemd:{distro}",
        )
        family = {
            "fedora-44": "fedora",
            "debian-13": "debian",
            "ubuntu-26.04": "ubuntu",
            "archlinux": "arch",
        }[distro]
        content = content.replace("build/packages/fedora/", f"build/packages/{family}/")
        if distro == "ubuntu-26.04":
            content = content.replace(
                "# DISTRO_BROWSER_SOURCE", UBUNTU_BROWSER.rstrip()
            )
            content = content.replace(
                "# DISTRO_BROWSER_ARTIFACTS",
                "COPY build/packages/ubuntu/session.txt /build-support/packages/session.txt\nRUN /build-support/install-packages session\nCOPY --from=chromium-packages /chromium-debs/ /tmp/chromium-debs/",
            )
        if distro == "debian-13":
            content = content.replace(
                "# DISTRO_RUNTIME_CONFIG",
                "# KWin 6.3 cannot add another output to its virtual backend.\nRUN touch /etc/plasma/vnc-existing-output",
            )
        if distro == "archlinux":
            content = content.replace(
                "# DISTRO_RUNTIME_CONFIG",
                "# KWin 6.8 uses software OpenGL instead of the removed QPainter backend.\nRUN touch /etc/plasma/opengl-software-capture",
            )
        content = content.replace(
            "# syntax=docker/dockerfile:1\n",
            "# syntax=docker/dockerfile:1\n# Generated by build/render-dockerfiles.py; edit Dockerfile and build/ instead.\n",
            1,
        )
        path = ROOT / f"Dockerfile.{distro}"
        if options.check:
            if not path.exists() or path.read_text() != content:
                failures.append(path.name)
        else:
            path.write_text(content)
    if failures:
        raise SystemExit("Regenerate Dockerfiles: " + ", ".join(failures))


if __name__ == "__main__":
    main()
